/* Order matters: first matching channel wins */
const CLASSIFY_ORDER = ['whatsapp', 'imported', 'referral', 'phone', 'campaign', 'website'];

const channelOf = (lead) => {
  const src = norm(lead.leadSource);
  for (const key of CLASSIFY_ORDER) {
    const ch = CHANNELS.find((c) => c.key === key);
    if (ch.match.some((m) => src.includes(m))) return ch;
  }
  return CHANNELS.find((c) => c.key === 'other');
};

